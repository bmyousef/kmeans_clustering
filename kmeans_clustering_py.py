import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
from skimage import data

X, y = make_blobs(
    n_samples=1000,
    centers=4,
    random_state=42
)

# Step 2: Plot the dataset before applying K-Means
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], color='gray')
plt.title('Dataset Before Applying K-Means')
plt.xlabel('Feature 1')
plt.ylabel('Feature 2')
plt.savefig('kmeans_data_before.png')
plt.show()

# Step 3: Apply K-Means clustering
kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
labels = kmeans.fit_predict(X)

# Get the cluster centers
centers = kmeans.cluster_centers_

# Step 4: Plot the dataset after applying K-Means
plt.figure(figsize=(8, 6))
plt.scatter(X[:, 0], X[:, 1], c=labels, cmap='viridis',
            label='Data points')
plt.scatter(centers[:, 0], centers[:, 1],
            color='red', marker='X', s=250,
            label='Cluster Centers')

plt.title('Dataset After Applying K-Means')
plt.xlabel('Feature 1')
plt.ylabel('Feature 2')
plt.legend()
plt.savefig('kmeans_data_after.png')
plt.show()

image = data.coffee()
#originaL image
plt.figure(figsize=(8, 6))
plt.imshow(image)
plt.title("Coffee Image Before K-Means")
plt.axis("off")
plt.savefig("kmeans_image_before.png")
plt.show()

#Reshape the image into RGB pixels
pixels = image.reshape(-1, 3)

# Apply K-Means with 4 clusters
kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
labels = kmeans.fit_predict(pixels)

# Replace each pixel with its cluster center color
new_pixels = kmeans.cluster_centers_[labels]

# Reshape pixels back into the original image shape
new_image = new_pixels.reshape(image.shape).astype("uint8")

# Image after K-Means(reduces the number of colors used in an image.)
plt.figure(figsize=(8, 6))
plt.imshow(new_image)
plt.title("Coffee Image After K-Means")
plt.axis("off")
plt.savefig("kmeans_image_after.png")
plt.show()